def plist(tasks, label, figs, start=1):
    items, ans = [], []
    for i, t in enumerate(tasks, start):
        star = "★" if t["star"] else ""
        fig = f'<figure class="fig grid">{figs["grid_" + t["fig"]]}</figure>' if t["fig"] else ""
        items.append(f'<li><span class="no">{i}.{star}</span><div><p>{vec_html(html(t["text"]))}</p>{fig}</div></li>')
        sol = f'<span class="sol">{vec_html(html(t["sol"]))}</span>' if t["sol"] else ""
        ans.append(f'<li><span class="no">{i}.</span><div><b>{t["ans"]}</b>{sol}</div></li>')
    return ('<ol class="plist">\n' + "\n".join(items) + "\n</ol>\n"
            f'<!--T--><details><summary>Ответ · {label}</summary>\n<ol class="solve">'
            + "\n".join(ans) + "</ol></details><!--/T-->\n")


def oshibki_html(lst, start=1):
    out = []
    for k, o in enumerate(lst, start):
        lines = "".join(f'<div class="ln">{vec_html(html(w))}</div>' for w in o["wrong"])
        out.append(f'<div class="wrong"><span class="tag">Решение {k} <span class="stamp">неверно</span></span>\n'
                   f'<p class="cond">{vec_html(o["task"])}</p>\n<div class="calc">{lines}</div>\n'
                   f'<!--T--><details><summary>Где ошибка</summary><p>{vec_html(o["why"])}</p>'
                   f'<p class="ans"><b>Верный ответ:</b> {o["fix"]}</p></details><!--/T-->\n</div>')
    return "\n".join(out)


def build_page(total):
    src = (HERE / "src.html").read_text(encoding="utf-8")
    figs = figures()
    n1 = sum(len(x[3]) for x in TYPES1) + len(MIX)
    repl = {"@@CSS@@": (HERE.parent / "seriya.css").read_text(encoding="utf-8").strip(),
            "@@N@@": str(total), "@@N1@@": str(n1), "@@N2@@": str(total - n1),
            "@@MIX@@": plist(MIX, "смешанная серия", figs),
            "@@OSH1@@": oshibki_html(OSH1), "@@OSH2@@": oshibki_html(OSH2, len(OSH1) + 1),
            "@@NOTES@@": "\n".join(f"<li><strong>{b}</strong> {vec_html(t)}</li>" for b, t in NOTES)}
    for key, num, title, tasks in TYPES1:
        repl[f"@@T:{key}@@"] = plist(tasks, f"тип {num}", figs)
    for key, num, title, tasks, lead in TYPES2:
        repl[f"@@V:{key}@@"] = (f'<h3 id="{key}"><span class="lvl">Тип {num}</span>{title}</h3>\n'
                                f'<p class="lead">{vec_html(lead)}</p>\n' + plist(tasks, f"тип {num}", figs))
    for k, svg in figs.items():
        repl.setdefault(f"@@F:{k}@@", svg)
    for k, val in repl.items():
        if k.startswith("@@F:"):
            src = src.replace(k, val)
            continue
        assert k in src, f"в src.html нет {k}"
        src = src.replace(k, val)
    assert "@@" not in src, re.findall(r"@@[^@]+@@", src)[:3]
    parts = re.split(r"(<style>.*?</style>|<svg.*?</svg>|<[^>]+>)", src, flags=re.S)
    # в тексте (не в тегах, стилях и чертежах): неразрывный пробел в числах и стрелки векторов
    src = "".join(x if x.startswith("<") else vec_html(re.sub(r"(?<=\d) (?=\d{3}(?!\d))", "\u202f", x))
                  for x in parts)
    return html_doc(src)


