def isq(n):
    """Точный целый корень — или ошибка."""
    r = math.isqrt(int(n))
    assert r * r == n, f"√{n} не целый"
    return r


def nice(x):
    """float, который обязан быть «хорошим» числом, — в Fraction."""
    q = F(str(round(float(x), 6)))
    assert abs(float(q) - float(x)) < 1e-9, x
    return q


def decomp(a, b, c):
    """x, y из c = x·a + y·b (правило Крамера)."""
    d = F(a[0] * b[1] - a[1] * b[0])
    return F(c[0] * b[1] - c[1] * b[0]) / d, F(a[0] * c[1] - a[1] * c[0]) / d


def T(t, p=None, f=None, a=None, s="", x=None, star=False, fig=None):
    return dict(t=t, p=p or {}, f=f, a=a, s=s, x=x, star=star, fig=fig)


def dot(u, v):
    return sum(F(a) * F(b) for a, b in zip(u, v))


def vlen(u):
    """Длина вектора — только если она рациональна."""
    q = dot(u, u)
    n, d = math.isqrt(q.numerator), math.isqrt(q.denominator)
    assert n * n == q.numerator and d * d == q.denominator, f"|{u}|² = {q} — не точный квадрат"
    return F(n, d)


def comb(*pairs):
    """comb((k1, u1), (k2, u2), …) = k1·u1 + k2·u2 + …"""
    dim = len(pairs[0][1])
    return tuple(sum(F(k) * F(u[i]) for k, u in pairs) for i in range(dim))


