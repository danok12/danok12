def num(v, n=2):
    s = f"{abs(float(v)):,.{n}f}".replace(",", NB).replace(".", ",")
    return ("−" if float(v) < 0 and s.strip("0,") else "") + s


def sgn(v, n=2):
    return num(v, n) if float(v) == 0 else ("+" if v > 0 else "−") + num(abs(v), n)


