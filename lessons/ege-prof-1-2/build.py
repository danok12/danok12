def fmt_val(x):
    if isinstance(x, tuple):
        return "(" + "; ".join(fmt_val(v) for v in x) + ")"
    if isinstance(x, float):
        return fnum(nice(x))
    if isinstance(x, (int, F)):
        return fnum(x)
    return str(x)


def fill(tpl, vals):
    return tpl.format(**{k: fmt_val(v) for k, v in vals.items()})


def vec_html(s):
    return re.sub(r"@([A-Z]{2}|[a-z])", r'<span class="vec">\1</span>', s)


def vec_md(s):
    return re.sub(r"@([A-Z]{2}|[a-z])", lambda g: g[1] + "⃗", s)


def solve(t):
    p = t["p"]
    val = t["f"](p)
    assert val is not None, f"не сошлось: {t['t'][:50]}"
    a = F(t["a"])
    if isinstance(val, float):
        assert abs(val - float(a)) < 1e-9, f"{t['t'][:60]}…: посчитано {val}, ожидалось {a}"
    else:
        assert F(val) == a, f"{t['t'][:60]}…: посчитано {val}, ожидалось {a}"
    for k in range(0, 7):                      # ответ пишется в бланк
        if (a * 10 ** k).denominator == 1:
            break
    else:
        raise AssertionError(f"ответ {a} — не конечная десятичная дробь")
    vals = dict(p)
    if t["x"]:
        vals.update(t["x"](p))
    t["text"] = fill(t["t"], vals)                                  # в условии {a} — вектор a, если он есть
    t["sol"] = fill(t["s"], {**vals, "a": a}) if t["s"] else ""     # в решении {a} — ответ
    t["ans"] = fmt_val(a)
    return t


