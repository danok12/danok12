def f_inscribed():
    s = sk(-2, 2, -2, 2, scale=30); O = (0, 0); r = 1.6
    A, B, C = on_circle(O, r, 215), on_circle(O, r, 325), on_circle(O, r, 100)
    s.circle(O, r); s.poly([O, A], close=False, color=ACC); s.poly([O, B], close=False, color=ACC)
    s.poly([A, C, B], close=False); s.arc_angle(O, A, B, r=.35); s.arc_angle(C, A, B, r=.4)
    for p, n in ((A, 'A'), (B, 'B'), (C, 'C')): s.dot(p); lab_out(s, O, p, n)
    s.dot(O); s.label((0, .3), 'O'); return themed(s.svg())

def f_diameter():
    s = sk(-2, 2, -1.9, 2, scale=30); O = (0, 0); r = 1.6
    A, C, B = on_circle(O, r, 180), on_circle(O, r, 0), on_circle(O, r, 62)
    s.circle(O, r); s.poly([A, B, C]); s.seg(A, C, color=ACC, width=2.2); s.right_angle(B, A, C, s=.25)
    for p, n in ((A, 'A'), (B, 'B'), (C, 'C')): s.dot(p); lab_out(s, O, p, n)
    s.dot(O); s.label((0, -.3), 'O'); return themed(s.svg())

def f_tangents():
    s = sk(-1.5, 3.6, -1.7, 1.7, scale=30); O = (0, 0); r = 1.2; M = (3.2, 0)
    th = math.degrees(math.acos(r / 3.2)); A, B = on_circle(O, r, th), on_circle(O, r, -th)
    s.circle(O, r); s.poly([A, M, B], close=False, color=ACC); s.seg(O, A); s.seg(O, B)
    s.right_angle(A, O, M, s=.2); s.right_angle(B, O, M, s=.2)
    for p, n in ((A, 'A'), (B, 'B')): s.dot(p); lab_out(s, O, p, n)
    s.dot(M); s.label((M[0] + .25, 0), 'M'); s.dot(O); s.label((-.25, 0), 'O'); return themed(s.svg())

def f_cyclic():
    s = sk(-2, 2, -2, 2, scale=30); O = (0, 0); r = 1.6
    P = [on_circle(O, r, a) for a in (205, 300, 15, 115)]
    s.circle(O, r); s.poly(P); s.arc_angle(P[0], P[3], P[1], r=.35); s.arc_angle(P[2], P[1], P[3], r=.35)
    for p, n in zip(P, 'ABCD'): s.dot(p); lab_out(s, O, p, n)
    return themed(s.svg())

def f_tangential():
    s = sk(-2.4, 2.4, -1.4, 1.4, scale=30)
    T = [(-2, -1), (-.5, 1), (.5, 1), (2, -1)]
    s.poly(T); s.circle((0, 0), 1, color=ACC); s.dot((0, 0))
    for p, n in zip(T, 'ABCD'): lab_out(s, (0, 0), p, n, k=.25)
    return themed(s.svg())

def f_trap():
    s = sk(-.4, 5.4, -.6, 2.5, scale=30)
    A, B, C, D = (0, 0), (1.1, 2), (3.6, 2), (5, 0)
    s.poly([A, B, C, D]); M1, M2 = ((A[0] + B[0]) / 2, 1), ((C[0] + D[0]) / 2, 1)
    s.seg(M1, M2, color=ACC, width=2.2); s.seg(B, (1.1, 0), dash='4 3'); s.right_angle((1.1, 0), B, D, s=.2)
    s.label((2.45, 2.35), 'b', italic=True); s.label((2.5, -.35), 'a', italic=True)
    s.label((2.5, 1.27), 'm', italic=True, color=ACC); s.label((1.3, .6), 'h', italic=True)
    return themed(s.svg())

def f_iso():
    s = sk(-.4, 5.4, -.8, 2.4, scale=30)
    A, B, C, D = (0, 0), (1.3, 1.8), (3.7, 1.8), (5, 0)
    s.poly([A, B, C, D]); s.seg(B, (1.3, 0), dash='4 3'); s.seg(C, (3.7, 0), dash='4 3')
    s.seg((0, -.35), (1.3, -.35), color=ACC, width=2.2); s.seg((3.7, -.35), (5, -.35), color=ACC, width=2.2)
    s.text((.65, -.68), '(a−b)/2', size=11, color=ACC); s.text((4.35, -.68), '(a−b)/2', size=11, color=ACC)
    s.arc_angle(A, D, B, r=.45); s.arc_angle(D, A, C, r=.45)
    return themed(s.svg())

