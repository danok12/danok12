R = sp.Rational


def ans(v):
    return fmt_num(sp.nsimplify(v))


def round2(fr):
    """Округление до сотых (половина — вверх), точно."""
    v = Fr(fr) * 100
    q = math.floor(v + Fr(1, 2))
    return fmt_num(R(q, 100))


