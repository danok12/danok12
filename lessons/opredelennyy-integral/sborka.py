def tabl(rows, head=("№", "ответ", "≈")):
    s = '<div class="tw"><table><thead><tr>' + "".join(
        f"<th>{h}</th>" for h in head) + "</tr></thead><tbody>"
    for r in rows:
        s += "<tr>" + "".join(
            f'<td class="num">{c}</td>' if i else f"<td>{c}</td>"
            for i, c in enumerate(r)) + "</tr>"
    return s + "</table></div>"


