def h_vr(mach, L=L_SR):
    """Нвр, маш.-ч на 100 м3: база + добавка на каждые следующие 10 м сверх базы (пропорционально)."""
    _, _, _, a, b, L0, _ = mach
    return a if b is None else a + b * (L - L0) / 10


def line(mach, V, H=None):
    """Строка табл. 7 для одной машины."""
    H = h_vr(mach) if H is None else H
    return {"mach": mach, "V": V, "H": H, "M": H * V / 800, "Vdn": Fr(100 * M_SM * 8) / H}


def variant(lead, support):
    rows = [lead] + support
    n_lead = ceil(lead["M"] / (M_SM * T_DN))
    lead["n"] = n_lead
    for r in support:
        r["n_calc"] = n_lead * lead["Vdn"] / r["Vdn"]
        r["n"] = ceil(r["n_calc"])
    s = sum(r["M"] for r in rows)
    return {"rows": rows, "SUM_M": s, "V_PER_M": lead["V"] / s, "M_PER_V": s / lead["V"],
            "DAYS": lead["M"] / (n_lead * M_SM)}


H_SKR = h_vr(SKR_VED)
