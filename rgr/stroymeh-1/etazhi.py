# -*- coding: utf-8 -*-
"""Схемы 4 и 5: расчёт по поэтажной схеме и эпюры «по правилам строймеха».

Всё, что написано в документе в разделах про схемы 4 и 5, пересчитывается
здесь независимо от решателя rama.py и сверяется с ним:

  1. реакции — по этажам, сверху вниз (сначала второстепенный диск);
  2. M — по характерным сечениям, сумма моментов сил отсечённой части;
  3. Q — ТОЛЬКО по эпюре M:  Q = Q⁰ + (M_пр − M_лев)/l,
     M со знаком «+», если растянуто отмеченное (пунктирное) волокно,
     «лев» и «пр» — концы участка, если смотреть так, чтобы отмеченное
     волокно было снизу; Q⁰ = ±q·l/2 — балочная поперечная сила от
     нагрузки самого участка;
  4. N — вырезанием узлов: в уравнения ΣX = 0, ΣY = 0 узла входят
     найденные Q (положительная Q вращает узел по часовой стрелке)
     и внешние силы.

Точная арифметика — fractions.Fraction.
"""
from fractions import Fraction as F
from sistemy import shema4, shema5

l, h, q, P, m = 6, 4, 1, 20, 10
ok = True


def sver(name, mine, ref):
    global ok
    good = F(mine) == F(ref)
    ok &= good
    print(f"  {'ок ' if good else 'НЕТ'} {name:46s} {float(mine):9.3f} | решатель {float(ref):9.3f}")


def fmt(v):
    x = float(v)
    return f"{round(x):d}" if abs(x - round(x)) < 1e-9 else f"{x:.2f}".replace(".", ",")


# ====================================================================== схема 4
print("=" * 78)
print("СХЕМА 4. Поэтажная схема: диск II (H–R–B, заделка) — основной,")
print("диск I (S–K–C–H: стержень S + шарнир H = 3 связи) — второстепенный")
print("=" * 78)
s4 = shema4(); s4.solve(); R4 = s4.R

# --- этаж I: S(0;0), C(6;0), H(6;4).  Неизвестные: R_S (↑+), X_H (→+), Y_H (↑+)
# ΣM_H = 0:  R_S·(0 − 6) + [−F]·(−(0 − 4))... — пишем через плечи:
#   R_S вверх на плече 6 слева от H  -> по часовой: −6·R_S
#   F влево по линии y = 0, на 4 ниже H -> по часовой: −F·4
R_S = F(-P * h, l)                         # −6·R_S − 80 = 0
X_H = F(P)                                 # ΣX: −F + X_H = 0
Y_H = -R_S                                 # ΣY: R_S + Y_H = 0
print(f"этаж I:  R_S = {fmt(R_S)} (то есть {fmt(-R_S)} кН вниз);  X_H = {fmt(X_H)} →;  Y_H = {fmt(Y_H)} ↑")
sver("R_S", R_S, R4['R_S'])

# --- этаж II: на него в H давят −X_H (←) и −Y_H (↓); q ← на стойке R–B; m против часовой в R
R_Bx = X_H + q * h                         # ΣX: −20 − 4 + R_Bx = 0
R_By = Y_H                                 # ΣY: −13,33 + R_By = 0
# ΣM_B (против часовой +): давление в H (−20; −13,33) в точке (−6; +4) от B
mom = (-6) * (-Y_H) - 4 * (-X_H) + 2 * (q * h) + m       # 80 + 80 + 8 + 10
M_B = -mom
print(f"этаж II: R_Bx = {fmt(R_Bx)} →;  R_By = {fmt(R_By)} ↑;  M_B = {fmt(M_B)} (по часовой {fmt(-M_B)})")
sver("R_Bx", R_Bx, R4['R_Bx']); sver("R_By", R_By, R4['R_By']); sver("M_B", M_B, R4['M_B'])

# --- M по характерным сечениям (модуль и растянутое волокно); знак для Q:
# отмеченное волокно — снизу у горизонтальных стержней, изнутри рамы у стоек
print("\nM по сечениям (знак «+» — растянуто отмеченное волокно):")
M4 = {
    ('SK', 0): 0,
    ('SK', 1): -(-R_S) * (l // 2),            # 13,33·3 = 40, растянут верх
    ('KC', 1): -(-R_S) * l,                   # 13,33·6 = 80, верх
    ('CH', 0): -X_H * h,                      # 20·4 = 80, наружное (левое) волокно
    ('CH', 1): 0,                             # шарнир H
    ('HR', 0): 0,                             # шарнир H
    ('HR', 1): -Y_H * l,                      # 13,33·6 = 80, верх
    ('RRB', 0): -(Y_H * l + m),               # 80 + 10 = 90, наружное
    ('RRB', F(1, 2)): -(Y_H * l + X_H * 2 + q * 2 * 1 + m),   # 80 + 40 + 2 + 10
    ('RRB', 1): -(Y_H * l + X_H * h + q * h * 2 + m),         # 80 + 80 + 8 + 10
}
for (mem, t), v in M4.items():
    sver(f"M {mem} t={t}", v, s4.internal(mem, F(t))[2])

print("\nQ по эпюре M:  Q = Q⁰ + (M_пр − M_лев)/l")
uch4 = [  # участок, M_лев, M_пр, l, Q⁰ на левом конце (±ql/2)
    ('SK', M4[('SK', 0)], M4[('SK', 1)], 3, 0),
    ('KC', M4[('SK', 1)], M4[('KC', 1)], 3, 0),
    ('CH', M4[('CH', 0)], M4[('CH', 1)], 4, 0),
    ('HR', M4[('HR', 0)], M4[('HR', 1)], 6, 0),
    ('RRB', M4[('RRB', 0)], M4[('RRB', 1)], 4, F(q * h, 2)),
]
for mem, ml, mp, L, q0 in uch4:
    base = F(mp - ml, L)
    Ql, Qp = q0 + base, -q0 + base
    print(f"  {mem}: ({fmt(mp)} − ({fmt(ml)}))/{L} = {fmt(base)};  Q⁰ = ±{fmt(q0)}  ->  {fmt(Ql)} … {fmt(Qp)}")
    sver(f"Q {mem} начало", Ql, s4.internal(mem, F(0))[1])
    sver(f"Q {mem} конец", Qp, s4.internal(mem, F(1))[1])


def uzel(name, ends, ext):
    """Равновесие узла. ends — [(u, N, Q)], u — орт от узла вдоль стержня;
    сила от стержня на узел: N·u + Q·(u_y, −u_x) (положительная Q вращает
    узел по часовой). ext — внешние силы (Fx, Fy)."""
    sx = sum(N * u[0] + Q * u[1] for u, N, Q in ends) + sum(f[0] for f in ext)
    sy = sum(N * u[1] - Q * u[0] for u, N, Q in ends) + sum(f[1] for f in ext)
    print(f"  узел {name}: ΣX = {fmt(sx)}, ΣY = {fmt(sy)}")
    return sx, sy


print("\nN вырезанием узлов (проверка подстановкой найденных N):")
N = {mem: s4.internal(mem, F(0))[0] for mem in ('SK', 'CH', 'HR', 'RRB')}
Qn = lambda mem, t: s4.internal(mem, F(t))[1]
res = [
    uzel("S", [((1, 0), N['SK'], Qn('SK', 0))], [(0, R_S)]),
    uzel("C", [((-1, 0), N['SK'], Qn('KC', 1)), ((0, 1), N['CH'], Qn('CH', 0))], [(-P, 0)]),
    uzel("H", [((0, -1), N['CH'], Qn('CH', 1)), ((1, 0), N['HR'], Qn('HR', 0))], []),
    uzel("R", [((-1, 0), N['HR'], Qn('HR', 1)), ((0, -1), N['RRB'], Qn('RRB', 0))], []),
    uzel("B", [((0, 1), N['RRB'], Qn('RRB', 1))], [(R_Bx, R_By)]),
]
for sx, sy in res:
    ok &= (sx == 0 and sy == 0)
print("  N:", {k: fmt(v) for k, v in N.items()})

# ====================================================================== схема 5
print("\n" + "=" * 78)
print("СХЕМА 5. Основные: A–H₁ (заделка) и H₂–E (стержни B, C);")
print("второстепенный — H₁–H₂, лежит на концах основных")
print("=" * 78)
s5 = shema5(); s5.solve(); R5 = s5.R
V = F(q * l, 2)                                   # давление H₁–H₂ на каждую опору
R_Ay = q * l + V
M_A = q * l * F(l, 2) + V * l
# H₂ = 12, B = 15, F = 18, C = 21, E = 27;  ΣM_C = 0 (против часовой +)
R_B = F(V * 9 + P * 3 - m, 6)
R_C = V + P - R_B
print(f"верхний этаж H₁–H₂: V = q·l/2 = {fmt(V)} кН на каждую опору")
print(f"A–H₁:  R_Ay = {fmt(R_Ay)};  M_A = {fmt(M_A)}")
print(f"H₂–E:  R_B = {fmt(R_B)};  R_C = {fmt(R_C)};  проверка ΣM_B = "
      f"{fmt(V * 3 - P * 3 + R_C * 6 - m)}")
sver("R_Ay", R_Ay, R5['R_Ay']); sver("M_A", M_A, R5['M_A'])
sver("R_B", R_B, R5['R_B']); sver("R_C", R_C, R5['R_C'])

print("\nM по сечениям (отмеченное волокно — нижнее):")
M5 = {
    ('AH1', 0): -M_A,                                # 36, верх
    ('AH1', F(1, 2)): -(V * 3 + q * 3 * F(3, 2)),     # 9 + 4,5 = 13,5, верх
    ('AH1', 1): 0,
    ('H1H2', F(1, 2)): F(q * l * l, 8),              # 4,5, низ
    ('H2B', 1): -V * 3,                              # 9, верх
    ('BP', 1): R_C * 3 - m,                          # 30,5 − 10 = 20,5, низ (справа)
    ('PC', 1): -m,                                   # 10, верх
    ('CE', 1): -m,
}
for (mem, t), v in M5.items():
    sver(f"M {mem} t={t}", v, s5.internal(mem, F(t))[2])
nol = F(3) * 9 / (9 + F(41, 2))
print(f"  M = 0 на участке B–F в {fmt(nol)} м от B")

print("\nQ по эпюре M:")
uch5 = [
    ('AH1', -M_A, 0, 6, F(q * 6, 2)),
    ('H1H2', 0, 0, 6, F(q * 6, 2)),
    ('H2B', 0, -V * 3, 3, 0),
    ('BP', -V * 3, R_C * 3 - m, 3, 0),
    ('PC', R_C * 3 - m, -m, 3, 0),
    ('CE', -m, -m, 6, 0),
]
for mem, ml, mp, L, q0 in uch5:
    base = F(mp - ml, L)
    Ql, Qp = q0 + base, -q0 + base
    print(f"  {mem}: ({fmt(mp)} − ({fmt(ml)}))/{L} = {fmt(base)};  Q⁰ = ±{fmt(q0)}  ->  {fmt(Ql)} … {fmt(Qp)}")
    sver(f"Q {mem} начало", Ql, s5.internal(mem, F(0))[1])
    sver(f"Q {mem} конец", Qp, s5.internal(mem, F(1))[1])

print("\n" + ("ВСЁ СОШЛОСЬ С РЕШАТЕЛЕМ" if ok else "ЕСТЬ РАСХОЖДЕНИЯ"))
