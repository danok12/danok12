// ---------- разметка формул: x_{низ}, x^{верх} ----------
function rich(str, base = {}) {
  const runs = [];
  let i = 0, buf = "";
  const flush = () => { if (buf) { runs.push(new TextRun({ text: buf, font: FONT, ...base })); buf = ""; } };
  while (i < str.length) {
    const c = str[i];
    if ((c === "_" || c === "^") && str[i + 1] === "{") {
      flush();
      let j = i + 2, depth = 1;
      while (j < str.length && depth) { if (str[j] === "{") depth++; if (str[j] === "}") depth--; j++; }
      const inner = str.slice(i + 2, j - 1);
      runs.push(new TextRun({ text: inner, font: FONT, ...base, ...(c === "_" ? { subScript: true } : { superScript: true }) }));
      i = j;
    } else { buf += c; i++; }
  }
  flush();
  return runs;
}

