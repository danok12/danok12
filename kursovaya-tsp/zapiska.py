def num(v, n=2):
    """Число по-русски: 1 234,56; минус - дефисом."""
    s = f"{abs(float(v)):,.{n}f}".replace(",", NB).replace(".", ",")
    return ("-" if float(v) < 0 and s.strip("0,") else "") + s


def sgn(v, n=2):
    """Рабочая отметка со знаком: +0,15 / -0,25."""
    s = num(abs(v), n)
    return s if float(v) == 0 else ("+" if v > 0 else "-") + s


