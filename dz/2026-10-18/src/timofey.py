def task4():
    T = []
    T.append(Task('В урне 12 красных, 8 синих и 5 зелёных шаров. Наугад достают один шар. '
                  'Найдите вероятность того, что он синий.', ans(R(8, 12 + 8 + 5))))
    fav = sum(1 for a, b in product(range(1, 7), repeat=2) if a + b == 8)
    T.append(Task('Игральную кость бросают дважды. Найдите вероятность того, что в сумме выпадет 8 очков. '
                  'Результат округлите до сотых.', round2(Fr(fav, 36))))
    fav = sum(1 for s in product('ОР', repeat=3) if s.count('О') == 2)
    T.append(Task('Монету бросают три раза. Найдите вероятность того, что орёл выпадет ровно два раза.', ans(R(fav, 8))))
    T.append(Task('В соревнованиях участвуют 20 спортсменов: 7 из России, 5 из Китая, остальные из других стран. '
                  'Порядок выступлений определяется жребием. Найдите вероятность того, что первым будет выступать '
                  'спортсмен из Китая.', ans(R(5, 20))))
    T.append(Task('В среднем из 1200 фонариков 30 неисправны. Найдите вероятность того, что случайно выбранный '
                  'фонарик исправен.', ans(R(1200 - 30, 1200))))
    T.append(Task('На экзамене 40 билетов, Олег не выучил 6 из них. Найдите вероятность того, что ему попадётся '
                  'выученный билет.', ans(R(34, 40))))
    third = R(50 - 18, 2)
    T.append(Task('На конференции 50 докладов, она идёт три дня. В первый день 18 докладов, остальные распределены '
                  'поровну между вторым и третьим днями. Порядок докладов определяется жребием. Какова вероятность, '
                  'что доклад профессора М. окажется в третий день?', ans(third / 50)))
    nums = [n for n in range(10, 100)]
    T.append(Task('Наугад выбирают двузначное число. Найдите вероятность того, что оно делится на 5.',
                  ans(R(sum(1 for n in nums if n % 5 == 0), len(nums)))))
    # 21 ученик, 3 группы по 7; друг Андрея может оказаться на одном из 20 мест, в его группе 6 мест
    T.append(Task('В классе 21 учащийся, среди них два друга — Андрей и Сергей. Класс случайным образом делят на '
                  '3 равные группы. Найдите вероятность того, что Андрей и Сергей окажутся в одной группе.',
                  ans(R(6, 20))))
    T.append(Task('Фабрика выпускает сумки. В среднем на 160 качественных сумок приходится 8 сумок со скрытыми '
                  'дефектами. Найдите вероятность того, что купленная сумка окажется качественной. '
                  'Результат округлите до сотых.', round2(Fr(160, 168))))
    return T


