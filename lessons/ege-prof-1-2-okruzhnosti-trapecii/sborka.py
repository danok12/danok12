def fact(svg, html):
    return f'<div class="fact{" nofig" if not svg else ""}">{svg or ""}<div>{html}</div></div>'

def example(n, tag, cond, svg, sol, ans):
    return (f'<div class="ex"><div class="ex-head"><span class="tag">Пример {n}</span><span class="muted">{tag}</span></div>'
            f'<div class="ex-body"><div><p>{cond}</p>'
            f'<details><summary>Решение — сначала попробуй сама</summary><div class="sol">{sol}'
            f'<p class="answer">Ответ: {ans}</p></div></details></div>{svg}</div></div>')

def tasks(prefix, items):
    lis = ''.join(f'<li><span class="num">{prefix}{i}</span><div><p>{q}</p><p class="ansline">Ответ: __________</p>'
                  f'<div class="key">Ответ: {a}</div><!--/k--></div></li>' for i, (q, a) in enumerate(items, 1))
    return f'<ol class="tasks">{lis}</ol>'

def wrong(prefix, items):
    lis = ''.join(f'<li><span class="num">{prefix}{i}</span><div><p>{q}</p><div class="wrong"><span class="lbl">Решение ученика</span>'
                  f'<p>{w}</p></div><p class="ansline">Где ошибка и какой верный ответ? __________</p>'
                  f'<div class="key">{a}</div><!--/k--></div></li>' for i, (q, w, a) in enumerate(items, 1))
    return f'<ol class="tasks">{lis}</ol>'

