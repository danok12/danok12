def s10():
    # 40a + 10b = 0,44·50;  (a + b)/2 = 0,5;  кислоты в первом сосуде 40a
    a = (F(44, 100) * 50 - 10 * 1) / (40 - 10)
    b = 1 - a
    assert 0 < a < 1 and 0 < b < 1
    return 40 * a


