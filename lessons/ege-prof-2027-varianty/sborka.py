def fig_tangent():
    p = Plane(-5, 6, -4, 7, cell=24)
    p.curve(lambda x: 3.5 + 0.75*(x - 2) - 0.22*(x - 2)**2, -1.7, 6, width=2)
    p.line_through((-4, -1), (4, 5), width=1.6)
    p.seg((2, 0), (2, 3.5), width=1, dash='4 3')
    p.text(2.15, -0.55, 'x<tspan font-size="10" dy="3">0</tspan>', italic=True)
    p.text(-2.3, 3.9, 'y = f(x)', italic=True, size=13)
    return p.svg()

def fig_derivative():
    f = lambda x: (x + 5)*(x + 2)*(x - 1)*(x - 4)/25
    p = Plane(-7, 6, -4, 5, cell=24)
    p.curve(f, -5.5, 4.5, width=2)
    p.dot(-5.5, f(-5.5), hollow=True); p.dot(4.5, f(4.5), hollow=True)
    p.text(-2.2, 3.4, "y = f ′(x)", italic=True, size=13)
    return p.svg()

def fig_parabola():
    p = Plane(-6, 4, -5, 5, cell=24)
    p.curve(lambda x: -0.5*(x + 1)**2 + 4, -6, 4, width=2)
    return p.svg()

def fig_lines():
    p = Plane(-5, 5, -4, 6, cell=24)
    p.line_through((-3, 1), (3, 5), width=2)
    p.line_through((-2, 0), (4, 3), width=2)
    return p.svg()

