def build_page(total):
    src = (HERE / "src.html").read_text(encoding="utf-8")
    legk, _ = plist(LEGKIE, label="расчётные задачи")
    n_hard = sum(1 for t in SLOZHNYE if "text" in t)
    repl = {"@@CSS@@": (HERE.parent / "seriya.css").read_text(encoding="utf-8").strip(),
            "@@VOPROSY@@": voprosy_html(), "@@LEGKIE@@": legk, "@@SLOZHNYE@@": slozhnye_html(),
            "@@OSHIBKI@@": oshibki_html(), "@@TABLES@@": tables_html(),
            "@@N@@": str(total), "@@NL@@": str(len(VOPROSY) + len(LEGKIE)), "@@NH@@": str(n_hard),
            "@@NOTES@@": "\n".join(f"<li><strong>{b}</strong> {html(t)}</li>" for b, t in NOTES)}
    for k, val in repl.items():
        assert k in src, f"в src.html нет {k}"
        src = src.replace(k, val)
    assert "@@" not in src
    # пробел внутри многозначного числа — неразрывный (только в тексте, не в тегах и стилях)
    parts = re.split(r"(<style>.*?</style>|<[^>]+>)", src, flags=re.S)
    src = "".join(x if x.startswith("<") else re.sub(r"(?<=\d) (?=\d{3}(?!\d))", "\u202f", x) for x in parts)
    return html_doc(src)


