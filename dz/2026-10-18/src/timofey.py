def E(dist):
    return sum(v * p for v, p in dist)


def D(dist):
    m = E(dist)
    return sum((v - m) ** 2 * p for v, p in dist)


def table(values, probs):
    return ('<table class="t"><tr><td>$X$</td>' + ''.join('<td>$%s$</td>' % v for v in values) +
            '</tr><tr><td>$P$</td>' + ''.join('<td>$%s$</td>' % p for p in probs) + '</tr></table>')


def task6():
    T = []
    pv = 1 - R(1, 10) - R(3, 10) - R(4, 10)
    T.append(Task('Случайная величина $X$ задана таблицей распределения. Найдите $p$.' +
                  table([1, 2, 3, 4], ['0{,}1', '0{,}3', '0{,}4', 'p']), ans(pv)))
    dist = [(-2, R(1, 10)), (0, R(4, 10)), (1, R(3, 10)), (3, R(2, 10))]
    assert sum(p for _, p in dist) == 1
    T.append(Task('Найдите математическое ожидание случайной величины $X$.' +
                  table([-2, 0, 1, 3], ['0{,}1', '0{,}4', '0{,}3', '0{,}2']), ans(E(dist))))
    dist = [(0, R(1, 4)), (1, R(1, 2)), (2, R(1, 4))]
    T.append(Task('Найдите дисперсию случайной величины $X$.' +
                  table([0, 1, 2], ['0{,}25', '0{,}5', '0{,}25']), ans(D(dist))))
    T.append(Task('Дисперсия случайной величины равна 6,25. Найдите её стандартное отклонение.',
                  ans(sp.sqrt(R(625, 100)))))
    die = [(k, R(1, 6)) for k in range(1, 7)]
    T.append(Task('Игральную кость бросают один раз, $X$ — число выпавших очков. Найдите $E(X)$.', ans(E(die))))
    coin = [(s.count('О'), R(1, 8)) for s in product('ОР', repeat=3)]
    T.append(Task('Монету бросают три раза, $X$ — число выпавших орлов. Найдите математическое ожидание $X$.',
                  ans(E(coin))))
    n, p = 10, R(7, 10)
    binom = [(k, sp.binomial(n, k) * p ** k * (1 - p) ** (n - k)) for k in range(n + 1)]
    assert D(binom) == n * p * (1 - p)
    T.append(Task('Стрелок делает 10 выстрелов, вероятность попадания при каждом 0,7 (выстрелы независимы). '
                  '$X$ — число попаданий. Найдите дисперсию $X$.', ans(D(binom))))
    T.append(Task('$E(X)=3$, $E(Y)=-2$. Найдите $E(2X-3Y+1)$.', ans(2 * 3 - 3 * (-2) + 1)))
    T.append(Task('$D(X)=4$. Найдите $D(3X-5)$.', ans(3 ** 2 * 4)))
    lot = [(500, R(5, 1000)), (100, R(20, 1000)), (0, R(975, 1000))]
    T.append(Task('В лотерее 1000 билетов: 5 выигрышей по 500 рублей, 20 — по 100 рублей, остальные без выигрыша. '
                  '$X$ — выигрыш (в рублях) на один купленный билет. Найдите $E(X)$.', ans(E(lot))))
    return T


