def fmt(v):
    return str(v.numerator) if v.denominator == 1 else str(round(float(v), 6)).replace('.', ',')


def build():
    html_parts = []
    md = ['# Домашнее задание', '']
    ot = ['# Ответы (только для преподавателя)', '', 'Проверено скриптом `sborka.py`.', '']
    n = 0
    for i, (sec, items) in enumerate(TASKS.items(), 1):
        html_parts.append(f'<h2>{i}. {TITLES[sec]}</h2><ol start="{n + 1}">' +
                          ''.join(f'<li>{t}</li>' for t, _, _ in items) + '</ol>')
        md += [f'## {i}. {TITLES[sec]}', '']
        ot += [f'## {i}. {TITLES[sec]}', '']
        for t, a, u in items:
            n += 1
            md.append(f'{n}. {t}')
            ot.append(f'{n}. {fmt(a)} {u}')
        md.append('')
        ot.append('')
    page = f'''<!doctype html><html lang="ru"><head><meta charset="utf-8"><title>Домашнее задание</title>
<style>
@page{{margin:14mm 14mm}}
body{{font-family:"Times New Roman",serif;font-size:13pt;line-height:1.35;color:#000;background:#fff;margin:0}}
h1{{font-size:15pt;margin:0 0 6pt}} h2{{font-size:13pt;margin:12pt 0 6pt;break-after:avoid}}
ol{{margin:0;padding-left:8mm}} li{{margin:0 0 7pt;break-inside:avoid}}
</style></head><body><h1>Домашнее задание</h1>{"".join(html_parts)}</body></html>'''
    (HERE / 'zadachi.html').write_text(page, encoding='utf-8')
