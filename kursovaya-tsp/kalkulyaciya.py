"""Курсовая по ТСП, вариант 2: калькуляция затрат труда и машинного времени (п. 2.4.5,
табл. 12 методички) и график производства работ (п. 2.4.6, табл. 13).

Нормы - ЕНиР Е2-1 (номера параграфов, таблиц и строк сверены по страницам сборника):
машинист - один на машину, поэтому затраты труда механизированного процесса равны его
затратам машинного времени; самосвалы - норма Нвр.а = Тцикла / (Va.р · 60) из п. 2.3.2
(методичка, с. 29), водитель - один на самосвал. Группы грунта: супесь - экскаваторы I,
скреперы и бульдозеры II, ручная разработка I; песок и щебень - I. Объёмы - из модулей
расчёта; там, где норма дана на площадь, - площадь (для слоёв - сумма площадей слоёв).
ч.-дн и м.-см - по 8 ч.

График (табл. 13): вспомогательные операции - в составе основных (с. 33); продолжительность
t = Θ / n, приведённая к целому числу смен; уровень производительности Уп.т = Θ / (n · t) - в
пределах 85-110 % (с. 34); 2 смены в сутки (п. 2.3).
"""
from fractions import Fraction as Fr
from math import ceil
import raschet as R
import kotlovan as K
import balans as B
import raspredelenie as RS
import mashiny as MS

KK = B.K1
KP = RS.K_P                                           # kр
SM = MS.M_SM                                          # смен в сутки
HA = Fr(MS.TR["Ha"]).limit_denominator(10 ** 9)       # Нвр.а, маш.-ч на 1 м3 в разрыхлённом состоянии
TRUCK = MS.TR["name"]
F_SITE = Fr(R.A * R.A * R.NX * R.NY)                  # площадь площадки, м2
BUL = MS.BUL_RAZ[1].split(" ")[0]                     # ДЗ-35С
KAT_P = MS.KATOK_POD[1].split(" ")[0]                 # ДУ-31А
NIZ = [tuple(map(Fr, p)) for p in KK["NIZ"]]
P_NIZ = sum(abs(b[0] - a[0]) + abs(b[1] - a[1]) for a, b in zip(NIZ, NIZ[1:] + NIZ[:1]))   # периметр дна

# --- подчистка недобора: бульдозер толкает срезанный грунт к северной подошве (лист 6) ---
V_NED = KK["F_KN"] * Fr(MS.NEDOBOR, 100)              # объём недобора, м3
_right = (NIZ[3][0] - NIZ[1][0]) * (NIZ[4][1] - NIZ[2][1])           # правая часть дна
_left = (NIZ[1][0] - NIZ[0][0]) * (NIZ[4][1] - NIZ[0][1])            # левое крыло
L_NED = (_right * (NIZ[4][1] - NIZ[2][1]) / 2 + _left * (NIZ[4][1] - NIZ[0][1]) / 2) / (_right + _left)
B_RUCH = Fr("0.5")                                    # полоса у подошвы откосов - вручную (бульдозер не подходит)
F_RUCH = P_NIZ * B_RUCH

# --- обратная засыпка: площадь слоя - средняя по высоте пазухи; каток - в широкой зоне у съезда ---
HK = KK["HK"]
F_SL = Fr(KK["V_PAZ"]).limit_denominator(10 ** 6) / HK                # средняя площадь слоя засыпки, м2
X_ST = K.X0 + K.BX + K.D_ST                                          # наружная грань восточной стены
x_otk = NIZ[3][0] + KK["M"] * HK / 2                                 # откос на середине высоты
F_KAT = (x_otk - X_ST - MS.KATOK_MIN) * ((NIZ[4][1] - NIZ[2][1]) + KK["M"] * HK)
F_TRAMB = F_SL - F_KAT
N_SL = MS.N_SL
F_SYEZD = KK["V_S"] / MS.H_SL                                        # сумма площадей слоёв засыпки съезда

V_PESOK = RS.T3_PRIVOZ[0][1] + RS.T3_PRIVOZ[1][1]                    # песок, плотное тело
V_SHCH = RS.T3_PRIVOZ[2][1]                                          # щебень
V_SHORT = sum(RS.SHORT.values())                                     # недостающий грунт в насыпь

M6 = "Машинист 6 р."
VOD = "Водитель"


def row(name, unit, k_unit, vol, src, crew, h_man, h_mach, n_crew=1):
    """Строка табл. 12: k_unit - размер единицы (100 м3, 1000 м2 ...), vol - объём в физ. единицах."""
    q = Fr(vol) / k_unit                                              # объём в единицах нормы
    man = h_man * q if h_man is not None else None
    mach = h_mach * q if h_mach is not None else None
    return {"name": name, "unit": unit, "vol": q, "src": src, "crew": crew, "h_man": h_man, "h_mach": h_mach,
            "man_h": man, "man_d": man / 8 if man is not None else None,
            "mach_h": mach, "mach_s": mach / 8 if mach is not None else None}


H_SKR, H_TOL = MS.H_SKR, MS.H_SKR / MS.SKR_NA_TOLKACH
H_NED = Fr("0.38") + Fr("0.3") * (L_NED - 10) / 10                   # Е2-1-22, № 6б: до 10 м + на каждые 10 м
GROUPS = [
    ("Вертикальная планировка площадки", [
        row(f"Срезка растительного слоя бульдозером {BUL}", "1000 м²", 1000, F_SITE,
            "Е2-1-5, № 4б", M6, Fr("1.3"), Fr("1.3")),
        row(f"Рыхление грунта рыхлителем {MS.RYKHL[1].split(' на')[0]}", "100 м³", 100, MS.V_PL,
            "Е2-1-1, табл. 2, № 3в", M6, Fr("0.06"), Fr("0.06")),
        row(f"Разработка и перемещение грунта скреперами {MS.SKR_VED[1].split(',')[0]} на {MS.L_SR:.0f} м",
            "100 м³", 100, MS.V_PL_KR, "Е2-1-21, табл. 2, № 2б, 2г", M6, H_SKR, H_SKR),
        row(f"Работа трактора-толкача {MS.TOLKACH[1]}", "100 м³", 100, MS.V_PL_KR,
            "Е2-1-21, примеч. 2", M6, H_TOL, H_TOL),
        row(f"Доставка недостающего грунта из карьера самосвалами {TRUCK}", "м³", 1, V_SHORT * KP,
            "расчёт, п. 3.2", VOD, HA, HA),
        row(f"Разравнивание грунта в насыпи бульдозером {BUL}", "100 м³", 100, MS.V_NAS,
            "Е2-1-28, № 6д", M6, Fr("0.27"), Fr("0.27")),
        row(f"Уплотнение грунта насыпи катком {MS.KATOK[1].split(' ')[0]}", "100 м³", 100, MS.V_NAS,
            "Е2-1-29, табл. 4, № 2в", M6, Fr("0.25"), Fr("0.25")),
        row(f"Окончательная планировка площадки бульдозером {BUL}", "1000 м²", 1000, F_SITE,
            "Е2-1-36, № 5а", M6, Fr("0.23"), Fr("0.23")),
    ]),
    ("Разработка котлована и устройство дна", [
        row(f"Разработка грунта экскаватором {MS.EX_NAME} с погрузкой в самосвалы", "100 м³", 100, MS.V_K,
            "Е2-1-11, табл. 7, № 4а", M6, MS.H_EX, MS.H_EX),
        row(f"Транспортирование грунта в насыпь самосвалами {TRUCK}", "м³", 1, MS.V_K * KP,
            "расчёт, п. 3.2", VOD, HA, HA),
        row(f"Подчистка недобора бульдозером {BUL} с перемещением на {float(L_NED):.0f} м", "100 м³", 100, V_NED,
            "Е2-1-22, табл. 2, № 6б", M6, H_NED, H_NED),
        row("Зачистка дна у подошвы откосов и в углах вручную", "100 м²", 100, F_RUCH,
            "Е2-1-60, № 7а", "Землекоп 2 р.", Fr("4.6"), None),
        row(f"Доставка щебня для подсыпки самосвалами {TRUCK}", "м³", 1, V_SHCH * KP,
            "расчёт, п. 3.2", VOD, HA, HA),
        row(f"Разравнивание щебня бульдозером {BUL}", "100 м³", 100, KK["V_PODS"],
            "Е2-1-28, № 6а", M6, Fr("0.38"), Fr("0.38")),
        row(f"Уплотнение подсыпки катком {KAT_P}", "1000 м²", 1000, KK["F_KN"],
            "Е2-1-31, табл. 3, № 1а", M6, Fr("1.3"), Fr("1.3")),
    ]),
    ("Обратная засыпка", [
        row(f"Доставка песка для засыпки пазух и съезда самосвалами {TRUCK}", "м³", 1, V_PESOK * KP,
            "расчёт, п. 3.2", VOD, HA, HA),
        row(f"Засыпка пазух песком бульдозером {BUL}", "100 м³", 100, KK["V_PAZ"],
            "Е2-1-34, № 10а", M6, Fr("0.25"), Fr("0.25")),
        row("Разравнивание песка в пазухах вручную", "100 м²", 100, F_TRAMB * N_SL,
            "Е2-1-60, № 8а", "Землекоп 2 р.", Fr("3.5"), None),
        row(f"Уплотнение песка электротрамбовками {MS.TRAMB[1]}", "100 м²", 100, F_TRAMB * N_SL,
            "Е2-1-59, табл. 3, № 2а", "Землекоп 3 р.", Fr("1.9"), Fr("1.9")),
        row(f"Уплотнение песка в зоне у съезда катком {KAT_P}", "1000 м²", 1000, F_KAT * N_SL,
            "Е2-1-31, табл. 3, № 1а", M6, Fr("1.3"), Fr("1.3")),
        row(f"Засыпка съезда песком - разравнивание бульдозером {BUL}", "100 м³", 100, KK["V_S"],
            "Е2-1-28, № 6г", M6, Fr("0.22"), Fr("0.22")),
        row(f"Уплотнение песка на съезде катком {KAT_P}", "1000 м²", 1000, F_SYEZD,
            "Е2-1-31, табл. 3, № 1а", M6, Fr("1.3"), Fr("1.3")),
    ]),
]
ROWS = [r for _, g in GROUPS for r in g]
TOT_MAN_D = sum(r["man_d"] for r in ROWS)
TOT_MACH_S = sum(r["mach_s"] for r in ROWS if r["mach_s"] is not None)

# ---------- график (табл. 13): процессы, исполнители, смены, календарь ----------
# (наименование, строки калькуляции (группа, № в группе), ед. и объём - по основной операции,
#  исполнители [(профессия, n)], смен в сутки, день начала, смена начала)
G = {(gi, ri): r for gi, (_, g) in enumerate(GROUPS) for ri, r in enumerate(g)}
N_TR = MS.TR["N"]
PROC = [
    ("Срезка растительного слоя", [(0, 0)], (0, 0), [(M6, 1)], 2, 1, 1),
    ("Рыхление грунта выемок", [(0, 1)], (0, 1), [(M6, 1)], 2, 2, 1),
    ("Разработка и перемещение грунта скреперами с толкачом", [(0, 2), (0, 3)], (0, 2),
     [(M6 + " (скреперы, толкач)", MS.VAR2["rows"][0]["n"] + 1)], 2, 3, 1),
    ("Разравнивание грунта в насыпи", [(0, 5)], (0, 5), [(M6, 1)], 1, 14, 1),
    ("Уплотнение грунта насыпи катком", [(0, 6)], (0, 6), [(M6, 1)], 1, 15, 1),
    ("Разработка грунта в котловане с транспортированием в насыпь", [(1, 0), (1, 1)], (1, 0),
     [(M6, 1), (VOD, N_TR)], 2, 15, 1),
    ("Подчистка дна котлована, устройство подсыпки, доставка недостающего грунта в насыпь",
     [(1, 2), (1, 3), (1, 4), (1, 5), (1, 6), (0, 4)], (1, 6), [(M6, 1), ("Землекоп 2 р.", 1), (VOD, N_TR)], 2, 20, 2),
    ("Окончательная планировка площадки", [(0, 7)], (0, 7), [(M6, 1)], 2, 25, 1),
    ("Обратная засыпка пазух и съезда песком", [(2, k) for k in range(7)], (2, 1),
     [(M6, 1), ("Землекоп 2-3 р.", 2 + MS.N_TRAMB), (VOD, N_TR)], 2, 28, 1),
]
# машин в смену Ni по процессам графика - для проектных затрат машинного времени Мп = Σ Ni · ti (ТЭП, с. 36)
MACH_N = [1, 1, MS.VAR2["rows"][0]["n"] + 1, 1, 1, 1 + N_TR, 2 + N_TR, 1, 2 + MS.N_TRAMB + N_TR]
BREAK_AFTER = 27                     # после 27-го дня - устройство подземной части здания (вне карты)
SCHED = []
for name, keys, mk, crew, spd, d0, s0 in PROC:
    th = sum(G[k]["man_d"] for k in keys)                 # трудоёмкость Θ, чел.-дн (= чел.-см)
    mach = sum(G[k]["mach_s"] for k in keys if G[k]["mach_s"] is not None)
    n = sum(c for _, c in crew)
    t = ceil(th / n)                                       # смен (с. 34: t = Θ / n до целой смены)
    shifts = []                                            # занятые смены: (день, смена)
    d, s = d0, s0
    while len(shifts) < t:
        if s <= spd:
            shifts.append((d, s))
        s += 1
        if s > 2:
            d, s = d + 1, 1
    days = len({d for d, _ in shifts})
    m = G[mk]
    SCHED.append({"name": name, "unit": m["unit"], "vol": m["vol"], "th": th, "mach": mach, "crew": crew, "n": n,
                  "t": t, "spd": spd, "days": days, "upt": th / (n * t) * 100, "shifts": shifts})
N_DAYS = max(d for p in SCHED for d, _ in p["shifts"])
T_ZEML = N_DAYS                                            # продолжительность земляных работ, дн (без перерыва)
for q, nm in zip(SCHED, MACH_N):
    q["mach_n"] = nm

# ---------- технико-экономические показатели (п. 2.4.8) ----------
V_TOT = Fr(B.B1["SUM_V"]).limit_denominator(10 ** 6)       # грунт, переработанный в плотном теле: выемка + котлован
V_SKR = MS.V_PL                                            # скреперами (грунт выемок в насыпь)
V_BUL = MS.V_NAS + V_NED + KK["V_PODS"] + KK["V_PAZ"] + KK["V_S"]  # бульдозером: разравнивание, подчистка, засыпка
V_EXC = MS.V_K                                             # экскаватором
M_N = TOT_MACH_S                                           # нормативные затраты машинного времени, маш.-см
M_P = sum(q["mach_n"] * q["t"] for q in SCHED)             # проектные, маш.-см
M_P_ED = M_P / V_TOT                                       # на 1 м3
B_P = V_TOT / M_P                                          # проектная выработка в смену, м3/маш.-см
U_PT = M_N / M_P * 100                                     # уровень производительности труда, %

if __name__ == "__main__":
    f = lambda v, n=2: "-" if v is None else f"{float(v):,.{n}f}".replace(",", " ").replace(".", ",")
    print(f"Lнед = {f(L_NED)} м, Нвр подчистки = {f(H_NED, 3)}; ручная зачистка {f(F_RUCH)} м2 (периметр {f(P_NIZ)});"
          f" слой засыпки ср. {f(F_SL)} м2: трамбовки {f(F_TRAMB)}, каток {f(F_KAT)}; съезд {f(F_SYEZD)} м2;"
          f" Нвр.а = {f(HA, 4)}")
    for title, g in GROUPS:
        print(title)
        for r in g:
            print(f"  {r['name'][:62]:<62} {r['unit']:>8} {f(r['vol'], 3):>9} {r['src']:<24} {f(r['h_man'], 4):>7}"
                  f" {f(r['man_h']):>8} {f(r['man_d']):>7} | {f(r['h_mach'], 4):>7} {f(r['mach_h']):>8} {f(r['mach_s']):>7}")
    print(f"Итого: {f(TOT_MAN_D)} чел.-дн, {f(TOT_MACH_S)} маш.-см")
    print("График:")
    for k, q in enumerate(SCHED, 1):
        print(f"  {k:>2}. {q['name'][:56]:<56} Θ {f(q['th']):>7} маш {f(q['mach']):>7} n {q['n']:>2} t {q['t']:>3} "
              f"дн {q['days']:>3} ({q['spd']} см/сут) Уп.т {f(q['upt'], 1):>6} %  дни {q['shifts'][0][0]}-{q['shifts'][-1][0]}")
    print("Всего дней:", N_DAYS)
    print(f"ТЭП: V = {f(V_TOT)} м3 (скрепер {f(V_SKR)}, бульдозер {f(V_BUL)}, экскаватор {f(V_EXC)}); Мн = {f(M_N)},"
          f" Мп = {f(M_P)} маш.-см; Мп/V = {f(M_P_ED, 5)}; Вп = {f(B_P)} м3/маш.-см; Уп.т = {f(U_PT, 1)} %")
