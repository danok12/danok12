# -*- coding: utf-8 -*-
"""Опорные реакции схемы 1 (вариант 2, строка 2).

Система координат: начало в заделке A, ось x вправо, ось y вверх,
момент положителен против часовой стрелки.

Геометрия (по чертежу методички):
    A = (0, 0)      заделка в стене
    B = (l, 0)      верх стойки, конец ригеля
    C = (l, -h)     узел, от него вправо консоль
    K = (l, -2h)    свободный нижний конец
    D = (2l, -h)    конец консоли

Нагрузка:
    q  — горизонтальная, на участке B-C, направлена справа налево;
    F  — вертикальная вверх в точке D;
    m  — сосредоточенный момент в K, против часовой стрелки.
"""
from fractions import Fraction as F_

l, h = F_(6), F_(4)          # м
q = F_(1)                    # кН/м
F = F_(20)                   # кН
m = F_(10)                   # кН·м

A = (F_(0), F_(0))
B = (l, F_(0))
C = (l, -h)
K = (l, -2 * h)
D = (2 * l, -h)

# --- внешние силы: (точка приложения, вектор) ---------------------------
Q = q * h                                   # равнодействующая q
loads = [
    ("q (равнодействующая)", (l, -h / 2), (-Q, F_(0))),
    ("F",                    D,            (F_(0), F)),
]
moments = [("m", m)]                        # сосредоточенные моменты, против часовой


def mom(point, vec, about=A):
    """Момент силы относительно точки, против часовой стрелки — плюс."""
    rx, ry = point[0] - about[0], point[1] - about[1]
    return rx * vec[1] - ry * vec[0]


print("=" * 70)
print("СХЕМА 1. ОПОРНЫЕ РЕАКЦИИ")
print("=" * 70)
print(f"l = {float(l)} м;  h = {float(h)} м;  q = {float(q)} кН/м;  "
      f"F = {float(F)} кН;  m = {float(m)} кН·м")
print(f"равнодействующая распределённой нагрузки Q = q·h = "
      f"{float(q)}·{float(h)} = {float(Q)} кН, приложена в точке "
      f"({float(l)}; {float(-h/2)})")

print("\n-- кинематический анализ ------------------------------------------")
print("  дисков D = 1 (одна жёсткая ломаная), опорных связей C0 = 3 (заделка),")
print("  шарниров нет:  W = 3·D − 2·Ш − C0 = 3·1 − 0 − 3 = 0")
print("  система статически определима и геометрически неизменяема")

# --- уравнения равновесия ----------------------------------------------
Sx = sum(v[0] for _, _, v in loads)
Sy = sum(v[1] for _, _, v in loads)
SM = sum(mom(p, v) for _, p, v in loads) + sum(mv for _, mv in moments)

RAx = -Sx
RAy = -Sy
MA = -SM

print("\n-- ΣX = 0 ---------------------------------------------------------")
print(f"  R_Ax − Q = 0   →   R_Ax = Q = {float(RAx)} кН   (вправо)")
print("\n-- ΣY = 0 ---------------------------------------------------------")
print(f"  R_Ay + F = 0   →   R_Ay = −F = {float(RAy)} кН   "
      f"({'вниз' if RAy < 0 else 'вверх'}, модуль {abs(float(RAy))} кН)")
print("\n-- ΣM_A = 0 -------------------------------------------------------")
for name, p, v in loads:
    print(f"  момент от {name:22s} = {float(mom(p, v)):+9.2f} кН·м")
for name, mv in moments:
    print(f"  момент {name:25s} = {float(mv):+9.2f} кН·м")
print(f"  сумма моментов нагрузки        = {float(SM):+9.2f} кН·м")
print(f"  M_A = −({float(SM)}) = {float(MA)} кН·м   "
      f"({'по часовой стрелке' if MA < 0 else 'против часовой стрелки'}, "
      f"модуль {abs(float(MA))} кН·м)")

print("\n" + "=" * 70)
print("ОТВЕТ")
print("=" * 70)
print(f"  R_Ax = {abs(float(RAx)):.0f} кН  — {'вправо' if RAx > 0 else 'влево'}")
print(f"  R_Ay = {abs(float(RAy)):.0f} кН  — {'вверх' if RAy > 0 else 'вниз'}")
print(f"  M_A  = {abs(float(MA)):.0f} кН·м — "
      f"{'против часовой' if MA > 0 else 'по часовой стрелке'}")

# --- проверка: сумма моментов относительно другой точки ----------------
print("\n-- проверка: ΣM_K = 0 (все силы, включая реакции) -----------------")
all_forces = [("R_A", A, (RAx, RAy))] + [(n, p, v) for n, p, v in loads]
total = sum(mom(p, v, K) for _, p, v in all_forces) + m + MA
for n, p, v in all_forces:
    print(f"  {n:22s}: {float(mom(p, v, K)):+9.2f} кН·м")
print(f"  {'m':22s}: {float(m):+9.2f} кН·м")
print(f"  {'M_A':22s}: {float(MA):+9.2f} кН·м")
print(f"  ИТОГО: {float(total):+.6f} кН·м  ->  "
      f"{'проверка сошлась' if total == 0 else 'НЕВЯЗКА'}")

# --- как изменится ответ при обратном направлении m --------------------
MA_alt = -(SM - 2 * m)
print(f"\nЕсли момент m направлен по часовой стрелке, то M_A = "
      f"{float(MA_alt)} кН·м (модуль {abs(float(MA_alt))}); "
      f"R_Ax и R_Ay не меняются.")
