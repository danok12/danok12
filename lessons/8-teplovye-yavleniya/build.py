def solve(t):
    p = dict(t["p"])
    for k in ("q",):
        if k in p:
            p["qs"] = fsci(p[k], keep_zero=True)
    r = t["calc"](p)
    vals = {**p, **r}
    for k, x in r.items():
        if k == "Q" and isinstance(x, (int, F)):
            vals["Qk"] = F(x) / 1000
            vals["QM"] = F(x) / 10**6
            vals["QM1"] = fround(F(x) / 10**6, 1)
            vals["QM2"] = fround(F(x) / 10**6, 2)
            vals["Qs"] = fsci(x)
    for k, want in t.get("expect", {}).items():
        assert vals[k] == want, f"{t['text'][:40]}…: {k} = {vals[k]}, ожидалось {want}"
    t["vals"] = vals
    t["text_f"] = fill(t["text"], vals)
    t["sol_f"] = fill(t["sol"], vals) if t.get("sol") else ""
    t["ans_f"] = fill(t["ans"], vals)
    return t


