def task1():
    T = []
    AC, BC = 8, 6
    AB = sp.sqrt(AC ** 2 + BC ** 2)
    T.append(Task('В треугольнике $ABC$ угол $C$ равен $90^\\circ$, $AC=%d$, $BC=%d$. Найдите $\\sin A$.' % (AC, BC),
                  ans(BC / AB)))
    T.append(Task('В треугольнике $ABC$ $AC=BC$, угол $C$ равен $52^\\circ$. Найдите угол $A$. Ответ дайте в градусах.',
                  ans(R(180 - 52, 2))))
    T.append(Task('Внешний угол при вершине $B$ треугольника $ABC$ равен $124^\\circ$, угол $A$ равен $47^\\circ$. '
                  'Найдите угол $C$. Ответ дайте в градусах.', ans(124 - 47)))
    xx = sp.Symbol('x')
    small = sp.solve(xx + xx + 36 - 180, xx)[0]
    T.append(Task('Один угол параллелограмма на $36^\\circ$ больше другого. Найдите больший угол. Ответ дайте в градусах.',
                  ans(small + 36)))
    T.append(Task('Основания трапеции равны 9 и 21. Найдите больший из отрезков, на которые диагональ делит её '
                  'среднюю линию.', ans(max(R(9, 2), R(21, 2)))))
    T.append(Task('Хорда $AB$ стягивает дугу окружности в $118^\\circ$. Точка $C$ лежит на большей дуге. '
                  'Найдите угол $ACB$. Ответ дайте в градусах.', ans(R(118, 2))))
    T.append(Task('Из точки $A$ проведены касательные $AB$ и $AC$ к окружности с центром $O$ ($B$ и $C$ — точки касания). '
                  'Угол $BAC$ равен $64^\\circ$. Найдите угол $BOC$. Ответ дайте в градусах.', ans(360 - 90 - 90 - 64)))
    T.append(Task('Катеты прямоугольного треугольника равны 10 и 24. Найдите радиус описанной около него окружности.',
                  ans(sp.sqrt(10 ** 2 + 24 ** 2) / 2)))
    T.append(Task('Диагонали ромба равны 12 и 16. Найдите сторону ромба.', ans(sp.sqrt(6 ** 2 + 8 ** 2))))
    T.append(Task('Четырёхугольник $ABCD$ вписан в окружность, угол $A$ равен $71^\\circ$. Найдите угол $C$. '
                  'Ответ дайте в градусах.', ans(180 - 71)))
    return T


