def box(title, lines):
    """Рамка «Как объяснить» / «Запомни»."""
    t = doc.add_table(rows=1, cols=1)
    t.style = "Table Grid"
    c = t.rows[0].cells[0]
    shd = OxmlElement("w:shd"); shd.set(qn("w:val"), "clear"); shd.set(qn("w:fill"), "EAF2FA")
    c._tc.get_or_add_tcPr().append(shd)
    c.text = ""
    p = c.paragraphs[0]
    r = p.add_run(title); r.bold = True; r.font.size = Pt(12)
    for s in lines:
        q = c.add_paragraph()
        parts = s.split("**")
        for k, piece in enumerate(parts):
            if piece:
                rr = q.add_run(piece); rr.font.size = Pt(12); rr.bold = k % 2 == 1
        q.paragraph_format.space_after = Pt(2)
    doc.add_paragraph().paragraph_format.space_after = Pt(2)


def table(head, rows, widths, size=11, align=None):
    t = doc.add_table(rows=1 + len(rows), cols=len(head))
    t.style = "Table Grid"
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    for i, row in enumerate([head] + rows):
        for j, v in enumerate(row):
            c = t.rows[i].cells[j]
            c.width = Mm(widths[j])
            c.text = ""
            p = c.paragraphs[0]
            p.paragraph_format.space_after = Pt(0)
            p.paragraph_format.line_spacing = 1.0
            a = "c" if i == 0 or not align else align[j]
            p.alignment = {"c": WD_ALIGN_PARAGRAPH.CENTER, "l": WD_ALIGN_PARAGRAPH.LEFT}[a]
            r = p.add_run(str(v)); r.font.size = Pt(size); r.bold = i == 0
            if i == 0:
                shd = OxmlElement("w:shd"); shd.set(qn("w:val"), "clear"); shd.set(qn("w:fill"), "DCE6F0")
                c._tc.get_or_add_tcPr().append(shd)
    doc.add_paragraph().paragraph_format.space_after = Pt(2)


