"""Сверка shevelev_steel() из raschet_v3.py с таблицей 1 Шевелёва (стальные ВГП, ГОСТ 3262-75), с. 31-32.
Допуск: 1000i — 1 %; v — 0,03 м/с по абсолютной величине (в таблице v округлена до сотых,
а у DN20 при 0,50 л/с стоит 1,53, хотя по соседней строке 0,45 л/с -> 1,40 пропорционально выходит 1,55-1,56)."""
import importlib.util
import os
import sys
import contextlib
import io

spec = importlib.util.spec_from_file_location("r3", os.path.join(os.path.dirname(os.path.abspath(__file__)), "raschet_v3.py"))
r3 = importlib.util.module_from_spec(spec)
with contextlib.redirect_stdout(io.StringIO()):
    spec.loader.exec_module(r3)

# (DN, Q л/с, v по таблице, 1000i по таблице)
TOCHKI = [
    (15, 0.035, 0.21, 15.3), (15, 0.10, 0.59, 100.2), (15, 0.20, 1.18, 360.5), (15, 0.30, 1.77, 807.0), (15, 0.55, 3.24, 2712),
    (20, 0.065, 0.20, 9.84), (20, 0.20, 0.62, 73.5), (20, 0.50, 1.53, 414.9), (20, 0.80, 2.50, 1062),
    (25, 0.12, 0.22, 8.44), (25, 0.30, 0.56, 43.4), (25, 0.55, 1.03, 132.5), (25, 0.75, 1.40, 240.6), (25, 0.85, 1.59, 309.1),
    (32, 0.19, 0.20, 4.67), (32, 0.40, 0.42, 17.5), (32, 0.75, 0.78, 54.9), (32, 0.85, 0.89, 69.2),
    (40, 0.25, 0.20, 3.91), (40, 0.55, 0.44, 15.9), (40, 0.85, 0.68, 35.0),
    (50, 0.45, 0.21, 3.11), (50, 0.75, 0.35, 7.70), (50, 0.85, 0.40, 9.64),
]
hud_i = 0
hud_v = 0
for dn, q, vt, it in TOCHKI:
    v, i = r3.shevelev_steel(q, dn)
    dv, di = (v - vt) / vt * 100, (1000 * i - it) / it * 100
    hud_i = max(hud_i, abs(di))
    hud_v = max(hud_v, abs(v - vt))
    print(f"DN{dn:<3} Q={q:<6} v {round(v, 3):<6} (табл {vt:<5}) {dv:+5.1f}%   1000i {round(1000 * i, 1):<7} (табл {it:<6}) {di:+5.1f}%")
print(f"Наибольшее расхождение: 1000i {hud_i:.1f}%, v {hud_v:.3f} м/с")
assert hud_i < 1.0 and round(hud_v, 6) <= 0.03, "расчёт разошёлся с таблицей Шевелёва"
