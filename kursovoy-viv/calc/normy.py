def alpha_b2(np_, mode="interp"):
    """α по табл. Б.2. mode='interp' — линейная интерполяция;
    mode='floor' — ближайшее меньшее табличное NP (так сделано в примерах методички)."""
    if np_ < B2_NP[0]:
        return 0.200
    i = bisect.bisect_right(B2_NP, np_) - 1
    if i >= len(B2_NP) - 1 or mode == "floor":
        return B2[B2_NP[i]]
    x0, x1 = B2_NP[i], B2_NP[i + 1]
    return B2[x0] + (B2[x1] - B2[x0]) * (np_ - x0) / (x1 - x0)


def alpha(n, p, mode="interp"):
    """α = f(NP): табл. Б.1 при P > 0,1 и N <= 200, иначе Б.2 (п. 5.3 СП)."""
    if p > 0.1 and n <= 200:
        raise NotImplementedError("Случай табл. Б.1 — добавить двойную интерполяцию по N и P")
    return alpha_b2(n * p, mode)


