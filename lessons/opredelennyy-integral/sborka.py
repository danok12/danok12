def I(lo, hi):
    """Знак интеграла с пределами."""
    return (f'<span class="I"><b>∫</b><span class="lm">'
            f'<i>{hi}</i><i>{lo}</i></span></span>')


def zvezdy(n):
    return '<span class="lv">' + "★" * n + '</span>'


def blok(nomer, nazvanie, vstupl, zadachi, otvety):
    """Один блок: заголовок, задачи, ответы под <details>."""
    s = f'<h2><span class="idx">Блок {nomer}</span>{nazvanie}</h2>\n'
    if vstupl:
        s += f"<p>{vstupl}</p>\n"
    s += '<div class="tasks">\n'
    for nom, lvl, telo in zadachi:
        s += (f'<div class="t"><div class="n">{nom} {zvezdy(lvl)}</div>'
              f'<div class="b">{telo}</div></div>\n')
    s += "</div>\n"
    s += ('<details><summary>Ответы блока ' + nomer + '</summary><div>\n'
          + otvety + '\n</div></details>\n')
    return s


def sobrat(html, dlya_ucheika):
    """Печатная копия: шрифты, тёмная тема, <details>, print-CSS."""
    h = re.sub(r'<link rel="stylesheet" href="https://fonts\.googleapis\.com[^>]*>',
               "", html)
    h = re.sub(r'@media \(prefers-color-scheme:dark\)\{.*?\n  \}\n\}\n', "", h,
               flags=re.S)
    h = re.sub(r':root\[data-theme="dark"\]\{.*?\n\}\n', "", h, flags=re.S)
    if dlya_ucheika:
        h = re.sub(r'<details>.*?</details>\n', "", h, flags=re.S)
        # фразы, осмысленные только на странице с раскрывающимися ответами
        h = re.sub(r'<span class="only-page">.*?</span>', "", h, flags=re.S)
    else:
        h = h.replace("<details>", "<details open>")
    h = h.replace("</style>", "</style>" + PRINT_CSS, 1)
    return ('<!doctype html><html lang="ru"><head><meta charset="utf-8">'
            '<meta name="viewport" content="width=device-width,initial-scale=1">'
            "</head><body>" + h + "</body></html>")


