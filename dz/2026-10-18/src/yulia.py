def lemma_tasks():
    T = [
        Task('Сформулируйте и докажите лемму о пересечении плоскости параллельными прямыми.',
             'если одна из двух параллельных прямых пересекает плоскость, то и другая прямая пересекает эту плоскость'),
        Task('Прямые $a$ и $b$ параллельны, прямая $a$ пересекает плоскость $\\alpha$. Может ли прямая $b$ лежать '
             'в плоскости $\\alpha$? Быть ей параллельной?', 'нет и нет: по лемме $b$ пересекает $\\alpha$'),
        Task('Прямая $a$ параллельна прямой $b$, прямая $b$ параллельна прямой $c$, прямая $c$ пересекает плоскость '
             '$\\alpha$. Докажите, что прямая $a$ тоже пересекает $\\alpha$.',
             '$a\\parallel c$ (теорема о трёх параллельных прямых), дальше лемма'),
    ]
    # через концы отрезка и середину проведены параллельные прямые: отрезок не пересекает плоскость
    aa, bb = 9, 15
    mm = R(aa + bb, 2)
    T.append(Task('Отрезок $AB$ не пересекает плоскость $\\alpha$. Через его концы и середину $M$ проведены '
                  'параллельные прямые, пересекающие $\\alpha$ в точках $A_1$, $B_1$, $M_1$. '
                  'Найдите $MM_1$, если $AA_1 = %d$ см, $BB_1 = %d$ см. Почему эти прямые вообще пересекают $\\alpha$?'
                  % (aa, bb), '$%s$ см (средняя линия трапеции); пересекают по лемме' % mm))
    aa, bb = 6, 14
    mm = abs(R(bb - aa, 2))
    T.append(Task('То же, но отрезок $AB$ пересекает плоскость $\\alpha$: $AA_1 = %d$ см, $BB_1 = %d$ см. Найдите $MM_1$.'
                  % (aa, bb), '$%s$ см' % mm, 'точки по разные стороны: $(14-6)/2$'))
    aa, bb = 4, 10
    cc = aa + R(1, 3) * (bb - aa)
    T.append(Task('Точка $C$ лежит на отрезке $AB$, причём $AC : CB = 1 : 2$; отрезок не пересекает плоскость $\\alpha$. '
                  'Через $A$, $B$, $C$ проведены параллельные прямые, пересекающие $\\alpha$ в точках $A_1$, $B_1$, $C_1$. '
                  'Найдите $CC_1$, если $AA_1 = %d$, $BB_1 = %d$.' % (aa, bb), '$%s$' % cc))
    return T


# ------------------------------------------------------------ сечения

def section_tasks():
    T = []
    figs = []

    def add(text, solid, pts, poly_pts, extra_ans='', width=200):
        poly = F.section(solid, *poly_pts)
        figs.append(F.svg(solid, pts, width=width))
        T.append(Task(text + '<br>' + figs[-1], F.describe(poly, pts) + extra_ans))
        return poly

    c = F.cube()
    poly = add('Постройте сечение куба $ABCDA_1B_1C_1D_1$ плоскостью $ACB_1$. Найдите периметр сечения, '
               'если ребро куба равно 4.', c, {}, (c.v['A'], c.v['C'], c.v['B1']))
    p4 = F.perimeter(F.section(F.cube(4), F.cube(4).v['A'], F.cube(4).v['C'], F.cube(4).v['B1']))
    T[-1].answer += '; правильный треугольник, $P=%s$' % tex_of(p4)

    M, N = F.point_on(c, 'A', 'A1', R(1, 2)), F.point_on(c, 'C', 'C1', R(1, 2))
    poly = add('$M$ и $N$ — середины рёбер $AA_1$ и $CC_1$ куба. Постройте сечение плоскостью $BMN$. '
               'Какая это фигура? Докажите.', c, {'M': M, 'N': N}, (c.v['B'], M, N))
    sides = {F.dist(poly[i][0], poly[(i + 1) % 4][0]) for i in range(4)}
    assert len(sides) == 1
    T[-1].answer += ' — ромб $BMD_1N$ (все стороны равны)'

    K, L, P = (F.point_on(c, 'B', 'A', R(1, 2)), F.point_on(c, 'B', 'C', R(1, 2)), F.point_on(c, 'B', 'B1', R(1, 2)))
    poly = add('$K$, $L$, $P$ — середины рёбер $AB$, $BC$, $BB_1$ куба. Постройте сечение плоскостью $KLP$ '
               'и найдите его площадь, если ребро куба равно 2.', c, {'K': K, 'L': L, 'P': P}, (K, L, P))
    c2 = F.cube(2)
    s2 = F.area(F.section(c2, F.point_on(c2, 'B', 'A', R(1, 2)), F.point_on(c2, 'B', 'C', R(1, 2)),
                          F.point_on(c2, 'B', 'B1', R(1, 2))))
    T[-1].answer += '; $S=%s$' % tex_of(s2)

    M, N = F.point_on(c, 'A', 'B', R(1, 2)), F.point_on(c, 'B', 'C', R(1, 2))
    add('$M$ и $N$ — середины рёбер $AB$ и $BC$ куба. Постройте сечение плоскостью $MND_1$ '
        '(метод следов: найдите, где прямая $MN$ пересекает прямые $AD$ и $DC$).', c, {'M': M, 'N': N},
        (M, N, c.v['D1']))

    t = F.tetra()
    M, N, Kp = F.point_on(t, 'D', 'A', R(1, 3)), F.point_on(t, 'D', 'B', R(1, 2)), F.point_on(t, 'B', 'C', R(1, 2))
    add('Тетраэдр $DABC$: $DM : MA = 1 : 2$, $N$ — середина $DB$, $K$ — середина $BC$. '
        'Постройте сечение плоскостью $MNK$.', t, {'M': M, 'N': N, 'K': Kp}, (M, N, Kp))

    M, N, Kp = F.point_on(t, 'D', 'A', R(1, 2)), F.point_on(t, 'D', 'B', R(1, 2)), F.point_on(t, 'D', 'C', R(1, 2))
    add('$M$, $N$, $K$ — середины рёбер $DA$, $DB$, $DC$ тетраэдра. Постройте сечение плоскостью $MNK$ и найдите '
        'его периметр, если $AB = 6$, $BC = 8$, $AC = 10$.', t, {'M': M, 'N': N, 'K': Kp}, (M, N, Kp))
    T[-1].answer += '; $P=%s$ (стороны — средние линии граней)' % ((6 + 8 + 10) // 2)

    M, N, Kp = F.point_on(t, 'A', 'D', R(1, 2)), F.point_on(t, 'D', 'C', R(1, 3)), F.point_on(t, 'A', 'B', R(1, 2))
    add('Тетраэдр $DABC$: $M$ — середина $AD$, $N$ на ребре $DC$, $DN : NC = 1 : 2$, $K$ — середина $AB$. '
        'Постройте сечение плоскостью $MNK$.', t, {'M': M, 'N': N, 'K': Kp}, (M, N, Kp))

    p = F.pyramid4()
    M, N = F.point_on(p, 'S', 'A', R(1, 2)), F.point_on(p, 'S', 'B', R(1, 2))
    poly = add('$SABCD$ — правильная четырёхугольная пирамида, $M$ и $N$ — середины $SA$ и $SB$. '
               'Постройте сечение плоскостью $MNC$. Какая это фигура?', p, {'M': M, 'N': N}, (M, N, p.v['C']))
    T[-1].answer += ' — трапеция $MNCD$ ($MN\\parallel AB\\parallel CD$)'

    r = F.prism3()
    M, N = F.point_on(r, 'A', 'B', R(1, 2)), F.point_on(r, 'A', 'C', R(1, 2))
    add('$ABCA_1B_1C_1$ — треугольная призма, $M$ и $N$ — середины $AB$ и $AC$. Постройте сечение плоскостью '
        '$MNC_1$. Почему в сечение попадает вершина $B_1$?', r, {'M': M, 'N': N}, (M, N, r.v['C1']))
    T[-1].answer += ' — трапеция $MNC_1B_1$'

    b = F.box(R(13, 10), 1, R(9, 10))
    M, N, Kp = F.point_on(b, 'A', 'A1', R(2, 3)), F.point_on(b, 'B', 'C', R(1, 2)), F.point_on(b, 'D1', 'C1', R(1, 3))
    add('★ Параллелепипед $ABCDA_1B_1C_1D_1$: $AM : MA_1 = 2 : 1$, $N$ — середина $BC$, '
        '$D_1K : KC_1 = 1 : 2$. Постройте сечение плоскостью $MNK$.', b, {'M': M, 'N': N, 'K': Kp}, (M, N, Kp), width=230)

    c6 = F.cube(6)
    s = F.area(F.section(c6, c6.v['B'], c6.v['D'], c6.v['B1']))
    T.append(Task('Ребро куба $ABCDA_1B_1C_1D_1$ равно 6. Постройте сечение плоскостью $BDB_1$ и найдите его площадь.',
                  'прямоугольник $BB_1D_1D$, $S=%s$' % tex_of(s)))
    t8 = F.regular_tetra(8)
    s = F.area(F.section(t8, F.point_on(t8, 'D', 'A', R(1, 2)), F.point_on(t8, 'D', 'B', R(1, 2)),
                         F.point_on(t8, 'D', 'C', R(1, 2))))
    T.append(Task('Ребро правильного тетраэдра $DABC$ равно 8. Найдите площадь сечения, проходящего через середины '
                  'рёбер $DA$, $DB$, $DC$.', '$S=%s$' % tex_of(s)))
    return T


# ------------------------------------------------------------ уравнения

ALG = [
    r'x^4-5x^2+4=0',
    r'\frac{x}{x-2}+\frac{3}{x+2}=\frac{8}{x^2-4}',
    r'\sqrt{x+5}=3',
    r'\sqrt{3x-2}=x-2',
    r'\sqrt{2x+7}=x+2',
    r'\sqrt{x^2-5}=2',
    r'\sqrt{x+4}+\sqrt{x-1}=5',
    r'3^{x+2}=81',
    r'2^{x^2-x}=4',
    r'5^{2x}-6\cdot5^{x}+5=0',
    r'4^{x}-3\cdot2^{x}-4=0',
    r'2^{x+1}+2^{x}=24',
    r'3^{x+1}-3^{x-1}=24',
    r'\left(\frac{1}{2}\right)^{x}=2^{3x-8}',
    r'\log_{2}(x-1)=3',
    r'\log_{3}(x^2-8x)=2',
    r'\lg x+\lg(x-3)=1',
    r'\log_{5}(x+1)=\log_{5}(2x-3)',
    r'\log_{\frac{1}{3}}(2x-1)=-2',
    r'\log_{2}(x+2)+\log_{2}(x-2)=5',
]

S, C = sp.sin(x), sp.cos(x)
TRIG = [
    (r'\sin x=\frac{1}{2}', S - R(1, 2), [(PI / 6, 2 * PI), (5 * PI / 6, 2 * PI)],
     r'\frac{\pi}{6}+2\pi n;\ \frac{5\pi}{6}+2\pi n'),
    (r'\cos x=-\frac{\sqrt{2}}{2}', C + sp.sqrt(2) / 2, [(3 * PI / 4, 2 * PI), (-3 * PI / 4, 2 * PI)],
     r'\pm\frac{3\pi}{4}+2\pi n'),
    (r'\tg x=\sqrt{3}', sp.tan(x) - sp.sqrt(3), [(PI / 3, PI)], r'\frac{\pi}{3}+\pi n'),
    (r'2\sin^2x-\sin x-1=0', 2 * S ** 2 - S - 1, [(PI / 2, 2 * PI), (-PI / 6, 2 * PI), (-5 * PI / 6, 2 * PI)],
     r'\frac{\pi}{2}+2\pi n;\ -\frac{\pi}{6}+2\pi n;\ -\frac{5\pi}{6}+2\pi n'),
    (r'\cos^2x+3\sin x-3=0', C ** 2 + 3 * S - 3, [(PI / 2, 2 * PI)], r'\frac{\pi}{2}+2\pi n'),
    (r'\sin2x=\sqrt{3}\cos x', sp.sin(2 * x) - sp.sqrt(3) * C, [(PI / 2, PI), (PI / 3, 2 * PI), (2 * PI / 3, 2 * PI)],
     r'\frac{\pi}{2}+\pi n;\ \frac{\pi}{3}+2\pi n;\ \frac{2\pi}{3}+2\pi n'),
    (r'\sin^2x-\cos^2x=\frac{1}{2}', S ** 2 - C ** 2 - R(1, 2), [(PI / 3, PI), (-PI / 3, PI)], r'\pm\frac{\pi}{3}+\pi n'),
    (r'\tg x+3\ctg x=4', sp.tan(x) + 3 * sp.cot(x) - 4, [(PI / 4, PI), (sp.atan(3), PI)],
     r'\frac{\pi}{4}+\pi n;\ \arctg3+\pi n'),
]


def eq_tasks():
    out = [Task('$%s$' % e, roots_tex(roots_real(e))) for e in ALG]
    return out


def trig_tasks():
    out = []
    for tex, f, series, ans in TRIG:
        conds = [('ne0', S), ('ne0', C)] if 'tg' in tex else []
        verify(f, [(sp.sympify(o), sp.sympify(p)) for o, p in series], conds)
        out.append(Task('$%s$' % tex, '$%s,\\ n\\in\\mathbb{Z}$' % ans))
    return out


def build():
    doc = Doc('yulia', 'Юлия', 'Домашнее задание · стереометрия и уравнения')
    doc.h('Стереометрия. Аксиомы и следствия')
    doc.tasks(theory_tasks(), cols=1, answer_cols=1)
    doc.h('Лемма о пересечении плоскости параллельными прямыми')
    doc.tasks(lemma_tasks(), cols=1, answer_cols=1)
    doc.h('Построение сечений')
    doc.p('Стройте прямо на чертеже карандашом. Правила: 1) соединяем только точки, лежащие в одной грани; '
          '2) если две точки сечения лежат в одной грани, а третьей там нет — ищем точку пересечения прямой '
          'с продолжением ребра (след); 3) в параллельных гранях отрезки сечения параллельны.')
    doc.tasks(section_tasks(), cols=2, answer_cols=1)
    doc.h('Уравнения')
    doc.p('Делайте проверку или следите за ОДЗ: в уравнениях с корнем и логарифмом посторонние корни — обычное дело.')
    doc.h('Рациональные, с корнем, показательные, логарифмические', 3)
    doc.tasks(eq_tasks(), cols=2, answer_cols=4)
    doc.h('Тригонометрические', 3)
    doc.tasks(trig_tasks(), cols=2, answer_cols=2)
    return doc
