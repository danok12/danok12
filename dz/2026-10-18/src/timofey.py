def task5():
    T = []
    p = R(8, 10)
    T.append(Task('Стрелок попадает в мишень с вероятностью 0,8. Он стреляет три раза. Найдите вероятность того, '
                  'что первые два раза он попадёт, а в третий раз промахнётся.', ans(p * p * (1 - p))))
    T.append(Task('В магазине два автомата по продаже кофе. Вероятность того, что к вечеру в первом закончится кофе, '
                  'равна 0,1, во втором — 0,15, независимо друг от друга. Найдите вероятность того, что к вечеру '
                  'кофе останется хотя бы в одном автомате.', ans(1 - R(1, 10) * R(15, 100))))
    T.append(Task('Вероятность того, что новый чайник прослужит больше года, равна 0,93. Вероятность того, что '
                  'он прослужит больше двух лет, равна 0,87. Найдите вероятность того, что он прослужит меньше двух лет, '
                  'но больше года.', ans(R(93, 100) - R(87, 100))))
    T.append(Task('Вероятность того, что задача в сборнике — на тему «Окружность», равна 0,15, на тему '
                  '«Треугольники» — 0,3. Задач, относящихся к обеим темам, нет. Найдите вероятность того, что '
                  'случайно выбранная задача относится к одной из этих двух тем.', ans(R(15, 100) + R(3, 10))))
    T.append(Task('Стёкла для фар делают две фабрики: первая — 60% стёкол, вторая — 40%. Первая выпускает 2% '
                  'бракованных стёкол, вторая — 4%. Найдите вероятность того, что случайно купленное стекло '
                  'бракованное.', ans(R(6, 10) * R(2, 100) + R(4, 10) * R(4, 100))))
    q = R(6, 100)
    T.append(Task('В магазине два платёжных терминала. Каждый может быть неисправен с вероятностью 0,06 '
                  'независимо от другого. Найдите вероятность того, что оба терминала исправны.', ans((1 - q) ** 2)))
    outs = [(a, b) for a, b in product(range(1, 7), repeat=2) if a + b == 9]
    T.append(Task('Игральную кость бросили два раза. Известно, что в сумме выпало 9 очков. Найдите вероятность того, '
                  'что при втором броске выпало 6 очков.', ans(R(sum(1 for a, b in outs if b == 6), len(outs)))))
    p = R(6, 10)
    T.append(Task('Стрелок стреляет по мишени до первого попадания, но не более четырёх раз. Вероятность попадания '
                  'при каждом выстреле 0,6. Найдите вероятность того, что понадобится ровно три выстрела.',
                  ans((1 - p) ** 2 * p)))
    T.append(Task('Если шахматист А. играет белыми, он выигрывает у Б. с вероятностью 0,6; если чёрными — с '
                  'вероятностью 0,4. Они играют две партии, во второй меняя цвет фигур. Найдите вероятность того, '
                  'что А. выиграет обе партии.', ans(R(6, 10) * R(4, 10))))
    pp = sp.Symbol('p')
    sol = sp.solve(R(4, 10) * pp + R(2, 10) * (1 - pp) - R(35, 100), pp)[0]
    T.append(Task('Агрофирма закупает яйца в двух хозяйствах. В первом 40% яиц — высшей категории, во втором — 20%. '
                  'Всего высшую категорию получают 35% закупленных яиц. Найдите вероятность того, что яйцо, '
                  'купленное у этой агрофирмы, окажется из первого хозяйства.', ans(sol)))
    return T


