import json, sys
pages = open(sys.argv[1], encoding='utf-8').read().split('\f')
items = ["ВВЕДЕНИЕ","ИСХОДНЫЕ ДАННЫЕ","1 Водоснабжение здания","1.1 Выбор системы и схемы водоснабжения. Конструктивные решения",
 "1.2 Определение расчётных расходов воды","1.3 Гидравлический расчёт сети В1","1.4 Подбор счётчиков воды",
 "1.5 Требуемый напор и подбор насосной установки","2 Водоотведение здания","2.1 Выбор системы и схемы водоотведения. Конструктивные решения",
 "2.2 Проверка пропускной способности стояков","2.3 Расчёт горизонтальных трубопроводов и дворовой сети","ЗАКЛЮЧЕНИЕ","БИБЛИОГРАФИЧЕСКИЙ СПИСОК"]
res = {}
for it in items:
    key = it[:22]
    hit = next(i + 1 for i, pg in enumerate(pages) if i >= 3 and any(l.strip().startswith(key) for l in pg.splitlines()))
    res[it] = hit
json.dump(res, open(sys.argv[2], 'w', encoding='utf-8'), ensure_ascii=False)
print(res)
