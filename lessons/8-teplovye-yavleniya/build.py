def who_has(c, liquid=False):
    names = [k for k, v in C.items() if v == c]
    if liquid:
        names = [k for k in names if k not in ("лёд",)]
    assert len(names) == 1, f"c = {c}: в таблице {names}"
    return names[0]


def v(x):
    """Значение для подстановки в текст."""
    return fnum(x) if isinstance(x, (int, F)) else x


def fill(tpl, vals):
    return tpl.format(**{k: v(x) for k, x in vals.items()})


