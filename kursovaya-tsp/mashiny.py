M_KOV = V_GRK * Fr(RHO, 1000)                         # масса грунта в ковше, т


def truck(t):
    nm, Va, Pa, hp, ug, up = t
    Va, Pa, hp = Fr(Va), Fr(Pa), Fr(hp)
    r = {"name": nm, "Va": Va, "Pa": Pa, "hp": hp, "Ugr": ug, "Upor": up,
         "n1": Pa / M_KOV, "n2": Va / V_KOV}
    r["n"] = floor(min(r["n1"], r["n2"]))
    r["ok"] = 6 <= r["n"] <= 11
    r["Va_pl"] = r["n"] * V_GRK
    r["Tp"] = r["Va_pl"] * H_EX / 100 * 60
    r["Tgr"], r["Tpor"] = L_TR / ug * 60, L_TR / up * 60
    r["Tc"] = T_UP + r["Tp"] + r["Tgr"] + r["Tpor"] + T_UR + T_R + T_M
    r["N_calc"] = r["Tc"] / r["Tp"]
    r["N"] = ceil(r["N_calc"])
    r["Va_r"] = V_KOV * K_NAP * r["n"]
    r["Ha"] = r["Tc"] / (r["Va_r"] * 60)               # маш.-ч на 1 м3
    return r


