"""Сверка pavlovsky.py с таблицами Лукиных (табл. 3 d=100, табл. 5 d=150), n = 0,014.
Точки выписаны со страниц 17, 18, 23-26, 31; допуск сверки — 1 % (точность самих таблиц)."""
from pavlovsky import flow
# (d мм, уклон в тысячных, h/d, q л/с по таблице, v м/с по таблице) — выписано со страниц 17, 18, 23-25
TOCHKI = [
    (100, 10, 0.3, 0.948, 0.48), (100, 10, 0.5, 2.42, 0.62), (100, 10, 0.8, 4.73, 0.70),
    (100, 20, 0.3, 1.34, 0.68), (100, 20, 0.5, 3.42, 0.87), (100, 25, 0.5, 3.83, 0.97),
    (100, 30, 0.3, 1.64, 0.83), (100, 30, 0.5, 4.19, 1.07), (100, 30, 0.6, 5.63, 1.14),
    (100, 50, 0.5, 5.41, 1.38), (100, 100, 0.3, 3.00, 1.51),
    (150, 6, 0.5, 5.56, 0.63), (150, 8, 0.3, 2.51, 0.56), (150, 8, 0.6, 8.61, 0.78),
    (150, 10, 0.5, 7.17, 0.81), (150, 12, 0.3, 3.08, 0.69), (150, 15, 0.5, 8.78, 0.99),
    (150, 20, 0.3, 3.97, 0.89), (150, 30, 0.6, 16.7, 1.51), (150, 70, 0.8, 37.1, 2.44),
    (150, 100, 0.5, 22.7, 2.56), (150, 150, 0.3, 10.9, 2.44),
    # табл. 7, d = 250 (с. 31) — диаметра нет в проекте, проверка формулы на другом d
    (250, 3, 0.5, 15.3, 0.62), (250, 5, 0.3, 7.73, 0.62), (250, 6, 0.8, 42.3, 1.00),
]
hud = 0
for d, i, hd, qt, vt in TOCHKI:
    v, q = flow(d, i / 1000, hd, 0.014)
    dq, dv = (q - qt) / qt * 100, (v - vt) / vt * 100
    hud = max(hud, abs(dq), abs(dv))
    print(f"d={d:3d} i={i:3d}‰ h/d={hd}: q {round(q,3):7} (табл {qt:6})  {dq:+5.1f}%   v {round(v,3):6} (табл {vt:5})  {dv:+5.1f}%")
print(f"Наибольшее расхождение: {hud:.1f}%")
assert hud < 1.0, "расчёт разошёлся с таблицами Лукиных больше чем на 1 %"
