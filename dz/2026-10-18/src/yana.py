"""Яна, 11 класс: задание 19 (параметр), только аналитический способ, от лёгкого к среднему."""
from common import Doc
from params import yana as yana_params

MEMO = r'''<div class="box">
<p><b>Инструменты аналитического способа.</b></p>
<p>1. Старший коэффициент зависит от $a$ — сначала случай, когда он равен нулю: уравнение становится линейным.</p>
<p>2. Квадратное уравнение: $D>0$ — два корня, $D=0$ — один, $D<0$ — нет. При чётном $b$ удобно $\frac{D}{4}$.</p>
<p>3. Знаки корней — теорема Виета: $x_1x_2=\frac{c}{a}$, $x_1+x_2=-\frac{b}{a}$. Корни разных знаков $\Leftrightarrow\ \frac{c}{a}<0$.</p>
<p>4. Корни относительно числа $m$ при $a>0$ (здесь $a$ — старший коэффициент): оба больше $m$ $\Leftrightarrow\ D>0$, $f(m)>0$, $x_\text{в}>m$.</p>
<p>5. Если дискриминант — полный квадрат, корни выписываются явно, и задача сводится к неравенствам.</p>
<p>6. Замена $t=2^x$, $t=x^2$, $t=|x|$, $t=\sqrt{\ldots}$, $t=\sin x$ — и сразу ограничение на $t$. Считаем, сколько $x$ даёт каждое $t$.</p>
<p>7. ОДЗ и посторонние корни: корень, обращающий знаменатель в нуль или вне области определения, выбрасываем — и это может менять число корней.</p>
</div>'''


def build():
    doc = Doc('yana', 'Яна, 11 класс', 'Домашнее задание · задачи с параметром (задание 19)')
    doc.p('Решаем только аналитически — без графиков. В каждой задаче пишите ход решения полностью: '
          'какие случаи разобраны, какие условия выписаны и почему. Ответ — множество значений $a$.')
    doc.raw(MEMO)
    T = yana_params()
    doc.h('Уровень 1. Линейные и квадратные уравнения')
    doc.tasks(T[0:5], cols=1, answer_cols=1)
    doc.h('Уровень 2. Корни явно, ОДЗ, системы, замена')
    doc.tasks(T[5:11], cols=1, answer_cols=1)
    doc.h('Уровень 3. Средний уровень')
    doc.tasks(T[11:], cols=1, answer_cols=1)
    return doc
