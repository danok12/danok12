def roots(a, b, c):
    """Рациональные корни ax² + bx + c = 0 (иначе ошибка: числа в задаче подобраны неудачно)."""
    a, b, c = F(a), F(b), F(c)
    D = b * b - 4 * a * c
    n, d = D.numerator, D.denominator
    assert D >= 0 and isqrt(n) ** 2 == n and isqrt(d) ** 2 == d, ('D не квадрат', D)
    s = F(isqrt(n), isqrt(d))
    return sorted({(-b - s) / (2 * a), (-b + s) / (2 * a)})


def only_valid(rs, cond=lambda x: x > 0):
    good = [r for r in rs if cond(r)]
    assert len(good) == 1, (rs, good)
    return good[0]


