INK, ACC = 'currentColor', 'ACCENT'

def sk(*a, **k):
    k.setdefault('scale', 40); return Sketch(*a, ink=INK, accent=ACC, **k)

def lab_out(s, c, p, name, k=0.32):
    """подпись точки p снаружи от центра c"""
    dx, dy = p[0] - c[0], p[1] - c[1]; L = math.hypot(dx, dy) or 1
    s.label((p[0] + k * dx / L, p[1] + k * dy / L), name)

